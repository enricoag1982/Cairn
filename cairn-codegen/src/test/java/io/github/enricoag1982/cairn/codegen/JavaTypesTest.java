package io.github.enricoag1982.cairn.codegen;

import static io.github.enricoag1982.cairn.codegen.GeneratedSource.PACKAGE;
import static io.github.enricoag1982.cairn.codegen.GeneratedSource.document;
import static io.github.enricoag1982.cairn.codegen.GeneratedSource.generate;
import static io.github.enricoag1982.cairn.codegen.GeneratedSource.text;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.assertj.core.api.Assertions.tuple;

import io.github.enricoag1982.cairn.schema.ProblemCode;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** What the generator does with documents (design D5 of {@code add-java-type-generation}). */
class JavaTypesTest {

    @TempDir
    Path directory;

    private static String model(String origin, String body) {
        return "cairn: 1\norigin: { name: " + origin + ", version: \"1.0.0\" }\n" + body;
    }

    @Test
    void theOutputIsTheSameForTheSameDocumentsWhereverTheyAreAndInWhateverOrder() throws IOException {
        Path first = Files.createDirectories(directory.resolve("one"));
        Path second = Files.createDirectories(directory.resolve("two"));
        String reference = Files.readString(ReferenceDomain.DOCUMENT);
        Path inOne = document(first, "reference-model.cairn.yaml", reference);
        Path inTwo = document(second, "reference-model.cairn.yaml", reference);

        Generation.Generated original = generate(ReferenceDomain.DOCUMENT);

        assertThat(generate(inOne)).isEqualTo(original);
        assertThat(generate(inTwo)).isEqualTo(original);
        assertThat(generate(ReferenceDomain.DOCUMENT)).isEqualTo(original);
        assertThat(original.files()).extracting(GeneratedFile::path).isSorted();
    }

    @Test
    void everyFileSaysWhereItComesFromAndNotToEditIt() {
        Generation.Generated generated = generate(ReferenceDomain.DOCUMENT);

        assertThat(generated.files()).hasSize(14).allSatisfy(file -> {
            assertThat(file.text()).startsWith("// Generated by Cairn (cairn-codegen) from "
                    + "reference-model.cairn.yaml.\n// Do not edit: ");
            assertThat(file.text()).endsWith("}\n").doesNotContain("\r").doesNotContain("\t");
            assertThat(file.text()).as("no absolute path and no time stamp").doesNotContain(directory.toString())
                    .doesNotContain(ReferenceDomain.DOCUMENT.getParent().toString()).doesNotContainPattern("20\\d\\d-\\d\\d");
        });
    }

    @Test
    void theHeaderNamesAllDocumentsSortedByName() throws IOException {
        Path b = document(directory, "b.cairn.yaml", model("b", "entityTypes:\n  B: {}\n"));
        Path a = document(directory, "a.cairn.json", "{\"cairn\": 1, \"origin\": {\"name\": \"a\", \"version\": \"1.0.0\"}, "
                + "\"entityTypes\": {\"A\": {}}}");

        Generation.Generated generated = generate(b, a);

        assertThat(generated.files()).extracting(GeneratedFile::path)
                .containsExactly("com/example/generated/A.java", "com/example/generated/B.java");
        assertThat(generated.files()).allSatisfy(file -> assertThat(file.text())
                .startsWith("// Generated by Cairn (cairn-codegen) from a.cairn.json, b.cairn.yaml.\n"));
    }

    @Test
    void aPackageNameMustBeLegal() throws IOException {
        Path file = document(directory, "model.cairn.yaml", model("m", "entityTypes:\n  Thing: {}\n"));

        for (String name : List.of("", ".a", "a.", "a..b", "a-b", "1a", "a.int", "a.null", "a b")) {
            assertThatThrownBy(() -> JavaTypes.generate(List.of(file), name)).as(name)
                    .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("Not a package name");
        }
    }

    @Test
    void aDocumentThatCannotBeReadFailsWithAnException() {
        Path missing = directory.resolve("missing.cairn.yaml");

        assertThatThrownBy(() -> JavaTypes.generate(List.of(missing), PACKAGE))
                .isInstanceOf(UncheckedIOException.class).hasMessageContaining("missing.cairn.yaml");
    }

    @Test
    void noDocumentsGenerateNothing() {
        assertThat(JavaTypes.generate(List.of(), PACKAGE)).isEqualTo(new Generation.Generated(List.of()));
    }

    @Test
    void documentsThatNeedEachOtherInACycleAreReportedWithTheirProblems() throws IOException {
        Path one = document(directory, "one.cairn.yaml", model("one", "entityTypes:\n  A:\n    supertype: B\n"));
        Path two = document(directory, "two.cairn.yaml", model("two", "entityTypes:\n  B:\n    supertype: A\n"));

        Generation generation = JavaTypes.generate(List.of(one, two), PACKAGE);

        assertThat(generation).isInstanceOf(Generation.Failed.class);
        assertThat(((Generation.Failed) generation).problems()).extracting(DocumentProblem::document, problem ->
                problem.problem().code()).containsExactly(
                        tuple(one, ProblemCode.UNKNOWN_REFERENCE),
                        tuple(two, ProblemCode.UNKNOWN_REFERENCE));
    }

    @Test
    void typesThatNameTheSameRuleWithoutACommonSupertypeAreReportedAtTheSecond() throws IOException {
        Path file = document(directory, "rules.cairn.yaml", model("rules", """
                entityTypes:
                  First:
                    rules:
                      - { name: shared, version: 1 }
                  Second:
                    rules:
                      - { name: shared, version: 1 }
                """));

        Generation generation = JavaTypes.generate(List.of(file), PACKAGE);

        assertThat(generation).isInstanceOf(Generation.Failed.class);
        assertThat(((Generation.Failed) generation).problems()).singleElement().satisfies(problem -> {
            assertThat(problem.problem().code()).isEqualTo(ProblemCode.RULE_TYPE_MISMATCH);
            assertThat(problem.format()).contains("rules.cairn.yaml:").contains("Second.shared");
        });
    }

    @Test
    void theSameOriginInTwoDocumentsIsCheckedAsARegistryWouldCheckIt() throws IOException {
        Path one = document(directory, "one.cairn.yaml", model("shared", "entityTypes:\n  A: {}\n"));
        Path two = document(directory, "two.cairn.yaml", model("shared", "entityTypes:\n  B: {}\n"));

        Generation generation = JavaTypes.generate(List.of(one, two), PACKAGE);

        assertThat(generation).isInstanceOf(Generation.Failed.class);
        assertThat(((Generation.Failed) generation).problems()).singleElement().satisfies(problem -> {
            assertThat(problem.document()).isEqualTo(two);
            assertThat(problem.problem().code()).isEqualTo(ProblemCode.VERSION_NOT_INCREASED);
        });
    }

    @Test
    void relationshipTypesGetBuildersForTheGeneratedTypesOfTheirEnds() throws IOException {
        Generation.Generated generated = generate(directory, model("m", """
                entityTypes:
                  Org: {}
                  Branch:
                    supertype: Org
                relationshipTypes:
                  Has:
                    source: Org
                    target: Branch
                    targetsPerSource: "0..*"
                    sourcesPerTarget: "0..*"
                    inverseName: hasBranch
                """));

        assertThat(text(generated, "Has")).contains("static Relate relate(Ref source, Ref target)")
                .contains("static Relate relate(Org source, Branch target)")
                .contains("return relate(source.id(), target.id());")
                .contains("public interface Has extends TypedRelationship");
        assertThat(text(generated, "Org")).contains("case \"Org\" -> Snapshot.of(state);")
                .contains("case \"Branch\" -> Branch.Snapshot.of(state);");
    }
}
